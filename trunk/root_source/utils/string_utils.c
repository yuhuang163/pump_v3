 char *sec_strncpy(char *dest, const char *src, size_t n)
 {
     if(!dest || !src)
         return dest;
     
     if (n > 0) {
         strncpy(dest, src, n - 1);
         *(dest + n - 1) = '\0';
     }
 
     return dest;
 }
 